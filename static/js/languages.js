function changeLanguage(lang) {
    if (!translations[lang]) return;

    document.querySelectorAll('[data-translate]').forEach(function(element) {
        const key = element.getAttribute('data-translate');
        if (translations[lang][key]) {
            // Check if there's a nested element with class `.text`
            const textElement = element.querySelector('.text');
            if (textElement) {
                textElement.textContent = translations[lang][key];
            } else {
                // Otherwise, set textContent directly if no nested `.text` element is found
                element.textContent = translations[lang][key];
            }
        }
    });

    localStorage.setItem('selectedLanguage', lang);
}


// Load the saved language when the page is loaded
window.onload = function() {
    const savedLanguage = localStorage.getItem('selectedLanguage') || 'en';
    changeLanguage(savedLanguage);
};

function toggleLanguageOptions() {
    const options = document.querySelector('.language-options');
    options.style.display = (options.style.display === 'none' || options.style.display === '') ? 'flex' : 'none';
}

function setLanguage(lang) {
    document.body.classList.remove('lang-en', 'lang-ar', 'lang-ku');
    document.body.classList.add(`lang-${lang}`);
    changeLanguage(lang); // Ensure language change is applied
}

document.querySelectorAll('.language-options a').forEach(link => {
    link.addEventListener('click', function() {
        const lang = this.getAttribute('data-lang');
        setLanguage(lang);
        toggleLanguageOptions(); 
    });
});
